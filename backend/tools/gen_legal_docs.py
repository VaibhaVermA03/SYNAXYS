"""Render the legal drafts (single source: frontend/src/legal/*.json, which the web app shows at /legal/*) to Markdown in docs/legal/.
Run:  python backend/tools/gen_legal_docs.py   (the pure tests fail if the Markdown is out of date). Stdlib only."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "frontend" / "src" / "legal"
OUT = ROOT / "docs" / "legal"
NAMES = {"privacy": "PRIVACY_POLICY.md", "terms": "TERMS_OF_SERVICE.md", "security": "SECURITY_POLICY.md", "license": "LICENSE_NOTICE.md"}
PLACEHOLDER = re.compile(r"\[\[(.+?)\]\]")
TOKEN = re.compile(r"\{\{(\w+)\}\}")
OPERATOR = json.loads((SRC / "operator.json").read_text(encoding="utf-8"))  # the owner's real details: the ONLY file to edit for the legal pages


def fill(text: str) -> str:
    """Replace {{key}} with the value from operator.json (unknown keys stay visible so a typo is noticed)."""
    return TOKEN.sub(lambda m: str(OPERATOR.get(m.group(1), m.group(0))), text)


def inline(text: str) -> str:
    return PLACEHOLDER.sub(lambda m: f"**[{m.group(1)}]**", fill(text))


def render(doc: dict) -> str:
    out = [f"# {doc['title']}", ""]
    if placeholders(doc):  # the draft notice disappears once every detail has been filled in
        out += [f"> **{doc['banner']}**".replace("[[", "[").replace("]]", "]"), ""]
    if doc.get("effective"):
        out += [inline(doc["effective"]), ""]
    for s in doc["sections"]:
        out += [f"## {s['title']}", ""]
        for b in s["blocks"]:
            if "p" in b:
                out += [inline(b["p"]), ""]
            elif "note" in b:
                out += [f"> **{inline(b['note'])}**", ""]
            elif "ul" in b:
                out += [f"- {inline(i)}" for i in b["ul"]] + [""]
            elif "table" in b:
                t = b["table"]
                out += ["| " + " | ".join(t["head"]) + " |", "|" + "---|" * len(t["head"])]
                out += ["| " + " | ".join(inline(c).replace("|", "\\|") for c in r) + " |" for r in t["rows"]] + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def placeholders(doc: dict) -> list[tuple[str, str]]:
    """(placeholder text, section title) for every [[...]] in the document, in order."""
    found = []
    def scan(text, where):
        found.extend((m.group(1), where) for m in PLACEHOLDER.finditer(fill(text)))
    scan(doc.get("effective", ""), "header")
    for s in doc["sections"]:
        for b in s["blocks"]:
            for key in ("p", "note"):
                if key in b:
                    scan(b[key], s["title"])
            for item in b.get("ul", []):
                scan(item, s["title"])
            for row in b.get("table", {}).get("rows", []):
                for cell in row:
                    scan(cell, s["title"])
    return found


def unfilled_operator_values() -> dict[str, str]:
    return {k: v for k, v in OPERATOR.items() if not k.startswith("_") and PLACEHOLDER.search(str(v))}


def render_checklist(docs: dict) -> str:
    """Which values in frontend/src/legal/operator.json are still [[placeholders]], and which documents use them."""
    used: dict[str, list[str]] = {}
    for key, doc in docs.items():
        blob = json.dumps(doc, ensure_ascii=False)
        for tok in sorted(set(TOKEN.findall(blob))):
            used.setdefault(tok, []).append(doc["title"])
    todo = unfilled_operator_values()
    out = ["# Details still to be filled in", "",
           "Generated by `python backend/tools/gen_legal_docs.py`. Put your real details into **`frontend/src/legal/operator.json`** (the only file you edit for the legal pages), then run the generator again.",
           "Also edit the copyright line in `LICENSE` and the contact lines at the top of `SECURITY.md` by hand.", ""]
    if not todo:
        out += ["Nothing left: every value in `operator.json` is filled in.", ""]
    for k, v in todo.items():
        out.append(f"- [ ] `{k}`: {PLACEHOLDER.search(str(v)).group(1)} *(used in: {', '.join(used.get(k, ['-']))})*")
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    docs = {
        key: json.loads((SRC / f"{key}.json").read_text(encoding="utf-8"))
        for key in NAMES
    }
    for key, name in NAMES.items():
        (OUT / name).write_text(render(docs[key]), encoding="utf-8")
    (OUT / "PLACEHOLDERS.md").write_text(
        render_checklist(docs), encoding="utf-8"
    )
    print(f"{len(NAMES)} documents and the placeholder checklist written to docs/legal/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())